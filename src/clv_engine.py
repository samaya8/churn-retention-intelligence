"""Customer Lifetime Value (CLV) and revenue at-risk modeling engine for retail banking."""

from __future__ import annotations

from typing import Any, Dict, Optional


DISCOUNT_RATE: float = 0.08      # 8% annual cost of capital
NIM_RATE: float = 0.025          # 2.5% Net Interest Margin on customer deposit balance
SALARY_MARGIN_RATE: float = 0.010 # 1.0% annual interchange/transaction revenue from salary
CARD_ANNUAL_FEE: float = 50.0    # Annual credit card fee/interchange


class CLVEngine:
    """Calculates forward-looking Customer Lifetime Value (CLV) and portfolio Value-at-Risk."""

    def __init__(self, discount_rate: float = DISCOUNT_RATE, nim_rate: float = NIM_RATE):
        self.discount_rate = max(0.01, float(discount_rate))
        self.nim_rate = max(0.001, float(nim_rate))

    def calculate_annual_margin(
        self,
        balance: float,
        estimated_salary: float,
        num_of_products: int = 1,
        is_active_member: int = 1,
        has_cr_card: int = 1,
    ) -> float:
        """Estimate the annual net banking revenue/margin generated by a customer."""
        balance_margin = float(balance) * self.nim_rate
        salary_margin = float(estimated_salary) * SALARY_MARGIN_RATE
        card_revenue = CARD_ANNUAL_FEE if bool(has_cr_card) else 0.0

        base_revenue = balance_margin + salary_margin + card_revenue

        # Multi-product multiplier (+15% margin per additional product held)
        prod_mult = 1.0 + (0.15 * max(0, int(num_of_products) - 1))

        # Active engagement multiplier
        act_mult = 1.25 if bool(is_active_member) else 0.80

        annual_margin = base_revenue * prod_mult * act_mult
        return max(150.0, round(annual_margin, 2))

    def calculate_forward_clv(
        self,
        annual_margin: float,
        churn_prob: float,
        years: int = 3,
    ) -> float:
        """Compute discounted forward Customer Lifetime Value over T years."""
        p_churn = max(0.0, min(1.0, float(churn_prob)))
        retention_rate = 1.0 - p_churn
        d = self.discount_rate

        clv = 0.0
        for t in range(1, years + 1):
            clv += (annual_margin * (retention_rate ** t)) / ((1.0 + d) ** t)

        return max(0.0, round(clv, 2))

    def assess_customer_value(
        self,
        balance: float,
        estimated_salary: float,
        churn_prob: float,
        num_of_products: int = 1,
        is_active_member: int = 1,
        has_cr_card: int = 1,
        intervention_cost: float = 100.0,
        p_save: float = 0.30,
    ) -> Dict[str, Any]:
        """Perform full financial assessment including 3Y & 5Y CLV, Value-at-Risk, and retention ROI."""
        ann_margin = self.calculate_annual_margin(
            balance=balance,
            estimated_salary=estimated_salary,
            num_of_products=num_of_products,
            is_active_member=is_active_member,
            has_cr_card=has_cr_card,
        )

        clv_3yr = self.calculate_forward_clv(ann_margin, churn_prob, years=3)
        clv_5yr = self.calculate_forward_clv(ann_margin, churn_prob, years=5)

        # Value at Risk: Expected forward loss in revenue if customer churns
        value_at_risk = round(float(churn_prob) * clv_3yr, 2)

        # Retention Campaign Economics
        expected_saved_value = round(value_at_risk * float(p_save), 2)
        net_retention_roi = round(expected_saved_value - float(intervention_cost), 2)
        roi_pct = round((net_retention_roi / max(1.0, float(intervention_cost))) * 100.0, 1)

        # Customer Value Tiering
        if clv_3yr >= 5000.0:
            value_tier = "Tier 1: Premier Wealth Customer"
        elif clv_3yr >= 2500.0:
            value_tier = "Tier 2: Prime Growth Customer"
        elif clv_3yr >= 1000.0:
            value_tier = "Tier 3: Standard Retail Customer"
        else:
            value_tier = "Tier 4: Entry Core Account"

        return {
            "annual_customer_margin": ann_margin,
            "clv_3yr": clv_3yr,
            "clv_5yr": clv_5yr,
            "value_at_risk": value_at_risk,
            "value_tier": value_tier,
            "intervention_cost": round(float(intervention_cost), 2),
            "expected_saved_value": expected_saved_value,
            "net_retention_roi": net_retention_roi,
            "roi_pct": roi_pct,
            "is_retention_profitable": net_retention_roi > 0.0,
        }
